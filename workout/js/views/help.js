export function render() {
  const root = h('div', { class: 'view' });

  root.appendChild(h('header', { class: 'view-head' }, [
    h('h1', { text: 'Как пользоваться' }),
    h('p', { class: 'muted', text: 'Шесть шагов до первой тренировки и ответы на частые вопросы.' })
  ]));

  root.appendChild(h('section', { class: 'card' }, [
    h('h3', { class: 'card-title', text: 'С чего начать' }),
    h('div', { class: 'steps-num' }, STEPS.map(([n, title, text]) => h('div', { class: 'step-item' }, [
      h('span', { class: 'step-num', text: n }),
      h('div', {}, [
        h('div', { class: 'list-title', text: title }),
        h('p', { class: 'muted small', text })
      ])
    ])))
  ]));

  root.appendChild(h('section', { class: 'card tip' }, [
    h('h3', { class: 'card-title', text: '💾 Сохраняется ли всё?' }),
    h('p', { class: 'small', text: 'Да, автоматически и мгновенно. Кнопки «сохранить» нет: каждый подход, вес, заметка и замер записываются в память устройства сразу. Регистрация не нужна, данные никуда не отправляются.' }),
    h('p', { class: 'muted small', text: 'Что может стереть данные: очистка истории и данных сайтов в Safari, удаление иконки с экрана «Домой», режим «Частный доступ». История привязана к этому устройству — на другом телефоне она будет своей.' }),
    h('p', { class: 'small', text: 'Поэтому раз в месяц делайте резервную копию: «Настройки → Данные → Экспорт». Файл можно сохранить в iCloud или отправить себе в мессенджер, а на новом телефоне восстановить кнопкой «Импорт».' }),
    h('div', { class: 'row gap wrap' }, [
      h('button', { class: 'btn small', text: '⬇️ Сделать копию сейчас', onClick: () => S.downloadBackup() }),
      h('a', { class: 'btn small ghost', href: '#/settings', text: 'Настройки' })
    ])
  ]));

  root.appendChild(h('section', { class: 'card' }, [
    h('h3', { class: 'card-title', text: 'Частые вопросы' }),
    h('div', { class: 'list' }, FAQ.map(([q, a]) => {
      const answer = h('p', { class: 'muted small faq-a', text: a });
      const row = h('div', { class: 'faq' }, [
        h('button', {
          class: 'faq-q', onClick: () => { row.classList.toggle('open'); }
        }, [h('span', { text: q }), h('span', { class: 'chev', text: '⌄' })]),
        answer
      ]);
      return row;
    }))
  ]));

  root.appendChild(h('section', { class: 'card' }, [
    h('h3', { class: 'card-title', text: 'Обозначения' }),
    h('div', { class: 'list' }, [
      legend('✓', 'Подход выполнен — запускается таймер отдыха'),
      legend('Р', 'Разминочный подход, не идёт в тоннаж'),
      legend('⋯', 'Меню упражнения: замена, заметка, отдых, удаление'),
      legend('⟲', 'Суперсет — выполняется без отдыха со следующим упражнением'),
      legend('★', 'Избранное упражнение'),
      legend('≈', 'Оценка максимума на одно повторение (1ПМ)')
    ])
  ]));

  root.appendChild(h('a', { class: 'btn block', href: '#/install', text: '📱 Как поставить иконку на телефон' }));
  root.appendChild(h('p', { class: 'muted small center-text disclaimer', text: 'При хронических заболеваниях, травмах или беременности проконсультируйтесь с врачом перед началом тренировок.' }));

  S.state.seenHelp = true;
  S.save(false);
  return root;
}

function legend(sign, text) {
  return h('div', { class: 'list-row' }, [
    h('span', { class: 'legend-sign', text: sign }),
    h('span', { class: 'grow small', text })
  ]);
}
